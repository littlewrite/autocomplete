#!/usr/bin/env node

// Generate dart/lib/src/spec_handlers/handler_index.dart: a DEFERRED-import
// registry mapping each catalog command to the register function that owns its
// handlers. The store registers a command's handlers lazily, right when that
// command's JSON spec is loaded, so an app only loadLibrary()s the handler
// code for the commands it actually completes.
const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..');
const handlerDir = path.join(repo, 'dart/lib/src/spec_handlers');
const assetRoot = path.join(repo, 'dart/assets/specs');
const outPath = path.join(handlerDir, 'handler_index.dart');

const files = fs
  .readdirSync(handlerDir)
  .filter((f) => f.endsWith('.dart') && f !== 'handler_index.dart')
  .sort();

// 1) Each handler file exposes its own `register<X>Handlers`.
const fileReg = {};
for (const f of files) {
  const src = fs.readFileSync(path.join(handlerDir, f), 'utf8');
  const m = src.match(/void\s+(register\w+Handlers)\s*\(/);
  fileReg[f.replace('.dart', '')] = m ? m[1] : null;
}

// 2) Reverse map: handler id -> owning file.
const idToFile = {};
for (const f of files) {
  const src = fs.readFileSync(path.join(handlerDir, f), 'utf8');
  for (const m of src.matchAll(/manual\.[^'"]+/g)) {
    idToFile[m[0]] = f.replace('.dart', '');
  }
}

function jsonFiles(dir) {
  const result = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) result.push(...jsonFiles(file));
    else if (entry.name.endsWith('.json')) result.push(file);
  }
  return result;
}
const indexPath = path.join(assetRoot, 'index.json');
const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
const indexEntries = index.commands || {};

function walkRefs(node, set) {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    node.forEach((v) => walkRefs(v, set));
    return;
  }
  if (typeof node.handler === 'string') {
    const f = idToFile[node.handler];
    if (f) set.add(f);
    return;
  }
  for (const value of Object.values(node)) walkRefs(value, set);
}

// Every register function referenced by ANY shipped JSON file must be
// reachable so `registerMigratedJsonHandlers` stays a superset of shipped refs.
const shippedFiles = new Set();
for (const f of jsonFiles(assetRoot)) {
  if (path.basename(f) === 'index.json') continue;
  const filesHere = new Set();
  try {
    walkRefs(JSON.parse(fs.readFileSync(f, 'utf8')), filesHere);
  } catch (_) {
    continue;
  }
  for (const hf of filesHere) shippedFiles.add(hf);
}

// 3) index.json command -> its handler files (for per-command lazy loading).
// A command may reference handlers across SEVERAL files; the emitted map keeps
// every owning file so the lazy path registers all of them (not just one).
const cmdToRegs = new Map();
for (const [cmd, entry] of Object.entries(indexEntries)) {
  const p = path.join(assetRoot, entry.file || '');
  if (!fs.existsSync(p)) continue;
  const handlerFiles = new Set();
  try {
    walkRefs(JSON.parse(fs.readFileSync(p, 'utf8')), handlerFiles);
  } catch (_) {
    continue;
  }
  const regFiles = [...handlerFiles].filter((f) => fileReg[f]).sort();
  if (regFiles.length) cmdToRegs.set(cmd, regFiles);
  if (regFiles.length > 1) {
    console.warn(`[build-handler-index] ${cmd} spans handler files: ${regFiles.join(', ')}`);
  }
}

// `_reg<File>` symbol for a handler file stem (e.g. react_native -> _regReact_native).
const fnName = (f) => '_reg' + f[0].toUpperCase() + f.slice(1);

// 4) Emit the Dart file.
const allFiles = [...shippedFiles].filter((f) => fileReg[f]).sort();

const lines = [];
lines.push('// GENERATED by tools/build-handler-index.cjs — do not edit by hand.');
lines.push('// Regenerate after adding/renaming handlers:');
lines.push('//   node tools/build-handler-index.cjs');
lines.push('//');
lines.push('// Each command\'s dynamic handlers live in a DEFERRED library that is');
lines.push('// loadLibrary()ed only when that command\'s JSON spec is first loaded,');
lines.push('// so an app pays for handler code only for the commands it completes.');
lines.push('');
lines.push("import 'package:autocomplete/src/json_spec.dart';");
lines.push('');
for (const f of allFiles) {
  lines.push(`import '${f}.dart' deferred as ${f};`);
}
lines.push('');
for (const f of allFiles) {
  lines.push(`Future<void> _reg${f[0].toUpperCase() + f.slice(1)}(`);
  lines.push('    JsonHandlerRegistry r) async {');
  lines.push(`  await ${f}.loadLibrary();`);
  lines.push(`  ${f}.${fileReg[f]}(r);`);
  lines.push('}');
}
lines.push('');
lines.push('/// Every migrated handler registrar referenced by shipped JSON, one');
lines.push('/// per deferred handler library.');
lines.push('final List<Future<void> Function(JsonHandlerRegistry)>');
lines.push('    allHandlerRegistrars = [');
for (const f of allFiles) {
  lines.push(`  _reg${f[0].toUpperCase() + f.slice(1)},`);
}
lines.push('];');
lines.push('');
lines.push('/// Command name (as in index.json) -> the registers owning that');
lines.push('/// command\'s handlers. A command may own handlers in several files;');
lines.push('/// every registrar runs. Safe to call repeatedly (loadLibrary is');
lines.push('/// idempotent).');
lines.push('final Map<String, List<Future<void> Function(JsonHandlerRegistry)>>');
lines.push('    commandHandlerRegistrars = {');
for (const [cmd, files] of [...cmdToRegs.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`  '${cmd}': [${files.map(fnName).join(', ')}],`);
}
lines.push('};');
lines.push('');
lines.push('/// Register the handlers for [command] on demand (no-op if unknown).');
lines.push('Future<void> registerCommandHandlers(');
lines.push('    JsonHandlerRegistry registry, String command) async {');
lines.push('  final registrars = commandHandlerRegistrars[command];');
lines.push('  if (registrars == null) return;');
lines.push('  for (final registrar in registrars) {');
lines.push('    await registrar(registry);');
lines.push('  }');
lines.push('}');
lines.push('');
lines.push('/// Register every migrated handler, loading each deferred library.');
lines.push('Future<void> registerMigratedJsonHandlers(');
lines.push('    JsonHandlerRegistry registry) async {');
lines.push('  for (final registrar in allHandlerRegistrars) {');
lines.push('    await registrar(registry);');
lines.push('  }');
lines.push('}');
lines.push('');

fs.writeFileSync(outPath, lines.join('\n'));
const summary = {
  output: path.relative(repo, outPath),
  commands: cmdToRegs.size,
  deferredLibraries: allFiles.length,
};
console.log(JSON.stringify(summary, null, 2));
